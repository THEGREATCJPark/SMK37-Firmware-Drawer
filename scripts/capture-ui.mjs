import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const phase=process.argv[2]||'after';
const folder=`output/playwright/redesign/${phase}`;
await mkdir(folder,{recursive:true});
const browser=await chromium.launch({channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:1040},reducedMotion:'reduce'});
await page.goto('http://127.0.0.1:4173/');
await page.screenshot({path:`${folder}/01-library.png`,fullPage:true});
await page.getByRole('button',{name:'Frodhes 열기',exact:true}).click();
await page.screenshot({path:`${folder}/02-detail.png`});
await page.getByRole('button',{name:'파일 검사·설치 준비',exact:true}).click();
await page.screenshot({path:`${folder}/03-install.png`});
await page.getByRole('button',{name:'닫기',exact:true}).click();
await page.getByRole('button',{name:'백업과 이력',exact:true}).click();
await page.screenshot({path:`${folder}/04-backups.png`,fullPage:true});
await page.getByRole('button',{name:'포팅 작업실',exact:true}).first().click();
await page.screenshot({path:`${folder}/05-porting.png`,fullPage:true});
await page.getByRole('button',{name:'서랍 홈',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:`${folder}/06-mobile.png`});
console.log(`Captured six real UI states: ${folder}`);
await browser.close();
